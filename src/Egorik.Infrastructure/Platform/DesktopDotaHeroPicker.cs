    public static (int X, int Y) HeroConfirmPointForClient(int width, int height)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(width, 800);
        ArgumentOutOfRangeException.ThrowIfLessThan(height, 600);
        return (
            (int)Math.Round(width * HeroConfirmButtonXRatio),
            (int)Math.Round(height * HeroConfirmButtonYRatio));
    }

    public async ValueTask<DotaHeroPickResult> ConfigureAsync(
        bool enabled,
        CancellationToken cancellationToken = default)
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        cancellationToken.ThrowIfCancellationRequested();
        if (!OperatingSystem.IsWindows())
        {
            return new DotaHeroPickResult(false, "Пик героя поддерживается только в Windows.");
        }

        try
        {
            if (!enabled)
            {
                StopListener();
                RemoveOwnedConfiguration();
                return new DotaHeroPickResult(true, "Плагин «Пик героя» выключен.");
            }

            var dotaDirectory = FindDotaDirectory();
            if (dotaDirectory is null)
            {
                return new DotaHeroPickResult(
                    false,
                    "Не найдена установленная Dota 2 в библиотеках Steam.");
            }

            _configPath = Path.Combine(
                dotaDirectory,
                "game",
                "dota",
                "cfg",
                "gamestate_integration",
                "gamestate_integration_egorik.cfg");
            WriteConfiguration(_configPath);
            StartListener();

            var restartHint = IsDotaRunning()
                ? " Перезапусти Dota 2, чтобы она перечитала конфигурацию Game State Integration."
                : string.Empty;
            return new DotaHeroPickResult(
                true,
                "Плагин «Пик героя» включён." + restartHint);
        }
        catch (Exception exception) when (
            exception is IOException or UnauthorizedAccessException or
                SocketException or InvalidOperationException)
        {
            StopListener();
            return new DotaHeroPickResult(
                false,
                $"Не удалось подготовить плагин Dota 2: {exception.Message}");
        }
    }

    public async ValueTask<DotaHeroPickResult> PickAsync(
        string heroSearchText,
        CancellationToken cancellationToken = default)
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        cancellationToken.ThrowIfCancellationRequested();
        if (!OperatingSystem.IsWindows())
        {
            return new DotaHeroPickResult(false, "Пик героя поддерживается только в Windows.");
        }

        if (!IsSafeSearchText(heroSearchText))
        {
            return new DotaHeroPickResult(false, "Плагин передал некорректное имя героя.");
        }

        try
        {
            StartListener();
        }
        catch (Exception exception) when (exception is SocketException or InvalidOperationException)
        {
            return new DotaHeroPickResult(
                false,
                $"Не удалось запустить локальный приёмник состояния Dota 2: {exception.Message}");
        }

        string? gameState;
        DateTimeOffset receivedAt;
        lock (_syncRoot)
        {
            gameState = _gameState;
            receivedAt = _gameStateReceivedAt;
        }

        if (!string.Equals(gameState, ExpectedGameState, StringComparison.Ordinal) ||
            DateTimeOffset.UtcNow - receivedAt > MaximumStateAge)
        {
            return new DotaHeroPickResult(
                false,
                "Dota 2 не подтвердила активную стадию выбора героя. " +
                "Открой экран пика; после первого включения плагина перезапусти игру.");
        }

        if (!TryGetForegroundDotaProcess(out var dotaProcess, out var error))
        {
            return new DotaHeroPickResult(false, error);
        }

        using (dotaProcess)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (!SendRepeatedKey(VirtualKeyBack, 64))
            {
                return new DotaHeroPickResult(
                    false,
                    BuildWindowsInputError("очистку строки поиска"));
            }

            if (!SendUnicodeText(heroSearchText))
            {
                return new DotaHeroPickResult(
                    false,
                    BuildWindowsInputError("ввод имени героя"));
            }

            await Task.Delay(TimeSpan.FromMilliseconds(350), cancellationToken);
            if (!IsStillForegroundDota(dotaProcess.Id) || !SendKey(VirtualKeyReturn))
            {
                return new DotaHeroPickResult(
                    false,
                    "Фокус окна Dota 2 изменился до подтверждения героя.");
            }

            await Task.Delay(TimeSpan.FromMilliseconds(300), cancellationToken);
            if (!IsStillForegroundDota(dotaProcess.Id) ||
                !ClickHeroConfirmButton(dotaProcess.MainWindowHandle))
            {
                return new DotaHeroPickResult(
                    false,
                    "Герой найден, но Windows не смогла нажать кнопку «Выбрать» в Dota 2.");
            }
        }

        return new DotaHeroPickResult(
            true,
            $"Герой «{heroSearchText}» выбран в Dota 2.");
    }

    public async ValueTask<CommandResult> ExecuteAsync(
        PluginCapabilityRequest request,
        CancellationToken cancellationToken = default)
    {
        if (!string.Equals(request.PluginId, DotaHeroPickerPluginId, StringComparison.Ordinal) ||
            request.CommandId is not ("pick_hero" or "javascript"))
        {
            return CommandResult.Failure(
                "Capability Dota 2 отклонила неизвестный источник команды.",
                "plugin.command");
        }

        var result = await PickAsync(request.Value, cancellationToken);
        return result.IsSuccess
            ? CommandResult.Success(
                $"Пикаю героя «{request.EntityName}».",
                "plugin.command")
            : CommandResult.Failure(result.Message, "plugin.command");
    }

    async ValueTask<CommandResult> IPluginActivationService.ApplyAsync(
        bool enabled,
        CancellationToken cancellationToken)
    {
        var result = await ConfigureAsync(enabled, cancellationToken);
        return result.IsSuccess
            ? CommandResult.Success(result.Message, "plugin.activation")
            : CommandResult.Failure(result.Message, "plugin.activation");
    }

    public void Dispose()
    {
        if (_disposed)
        {
            return;
        }

        StopListener();
        _disposed = true;
    }

    [SupportedOSPlatform("windows")]
    private static string? FindDotaDirectory()
    {
        foreach (var process in Process.GetProcessesByName("dota2"))
        {
            using (process)
            {
                try
                {
                    var executable = process.MainModule?.FileName;
                    if (!string.IsNullOrWhiteSpace(executable))
                    {
                        var candidate = Path.GetFullPath(Path.Combine(
                            Path.GetDirectoryName(executable)!,
                            "..",
                            "..",
                            ".."));
                        if (IsDotaDirectory(candidate))
                        {
                            return candidate;
                        }
                    }
                }
                catch (Exception exception) when (
                    exception is InvalidOperationException or Win32Exception or NotSupportedException)
                {
                    // Проверяем библиотеки Steam.
                }
            }
        }

        return SteamGameCatalog.FindLibraries()
            .Select(library => Path.Combine(
                library,
                "steamapps",
                "common",
                "dota 2 beta"))
            .FirstOrDefault(IsDotaDirectory);
    }

    private static bool IsDotaDirectory(string directory) =>
        File.Exists(Path.Combine(directory, "game", "bin", "win64", "dota2.exe"));

    private static bool IsDotaRunning()
    {
        var processes = Process.GetProcessesByName("dota2");
        try
        {
            return processes.Length > 0;
        }
        finally
        {
            foreach (var process in processes)
            {
                process.Dispose();
            }
        }
    }

    private static void WriteConfiguration(string configPath)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(configPath)!);
        var contents = $$"""
                         {{ConfigHeader}}
                         "Egorik Dota 2 Integration"
                         {
                           "uri"           "http://127.0.0.1:{{GameStatePort}}/egorik-dota2/"
                           "timeout"       "2.0"
                           "buffer"        "0.1"
                           "throttle"      "0.1"
                           "heartbeat"     "1.0"
                           "auth"
                           {
                             "token"       "{{AuthenticationToken}}"
                           }
                           "data"
                           {
                             "provider"    "1"
                             "map"         "1"
                           }
                         }
                         """;
        File.WriteAllText(configPath, contents, new UTF8Encoding(false));
    }

    private void RemoveOwnedConfiguration()
    {
        var path = _configPath ?? FindExistingConfiguration();
        if (path is null || !File.Exists(path))
        {
            return;
        }

        using var reader = new StreamReader(path, Encoding.UTF8, true);
        var firstLine = reader.ReadLine();
        if (string.Equals(firstLine, ConfigHeader, StringComparison.Ordinal))
        {
            File.Delete(path);
        }
    }

    [SupportedOSPlatform("windows")]
    private static string? FindExistingConfiguration()
    {
        var dotaDirectory = FindDotaDirectory();
        return dotaDirectory is null
            ? null
            : Path.Combine(
                dotaDirectory,
                "game",
                "dota",
                "cfg",
                "gamestate_integration",
                "gamestate_integration_egorik.cfg");
    }

    private void StartListener()
    {
        lock (_syncRoot)
        {
            if (_listenerTask is { IsCompleted: false })
            {
                return;
            }

            _listenerCancellation?.Dispose();
            _listenerCancellation = new CancellationTokenSource();
            _listener = new TcpListener(IPAddress.Loopback, GameStatePort);
            _listener.Start(4);
            _listenerTask = ListenAsync(_listener, _listenerCancellation.Token);
        }
    }

    private void StopListener()
    {
        TcpListener? listener;
        CancellationTokenSource? cancellation;
        lock (_syncRoot)
        {
            listener = _listener;
            cancellation = _listenerCancellation;
            _listener = null;
            _listenerCancellation = null;
            _listenerTask = null;
            _gameState = null;
            _gameStateReceivedAt = default;
        }

        cancellation?.Cancel();
        listener?.Stop();
        cancellation?.Dispose();
    }

    private async Task ListenAsync(TcpListener listener, CancellationToken cancellationToken)
    {
        while (!cancellationToken.IsCancellationRequested)
        {
            try
            {
                var client = await listener.AcceptTcpClientAsync(cancellationToken);
                _ = ProcessClientAsync(client, cancellationToken);
            }
            catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
            {
                return;
            }
            catch (SocketException) when (cancellationToken.IsCancellationRequested)
            {
                return;
            }
        }
    }

    private async Task ProcessClientAsync(
        TcpClient client,
        CancellationToken cancellationToken)
    {
        using (client)
        {
            try
            {
                var stream = client.GetStream();
                var body = await ReadHttpBodyAsync(stream, cancellationToken);
                UpdateGameState(body);
                var response = "HTTP/1.1 200 OK\r\nContent-Type: application/json\r\n" +
                               "Content-Length: 2\r\nConnection: close\r\n\r\n{}";
                await stream.WriteAsync(Encoding.ASCII.GetBytes(response), cancellationToken);
            }
            catch (Exception exception) when (
                exception is IOException or JsonException or InvalidDataException or SocketException ||
                exception is OperationCanceledException && cancellationToken.IsCancellationRequested)
            {
                // Недоверенный или оборванный локальный запрос не меняет состояние.
            }
        }
    }

    private static async Task<byte[]> ReadHttpBodyAsync(
        NetworkStream stream,
        CancellationToken cancellationToken)
    {
        using var request = new MemoryStream();
        var buffer = new byte[4096];
        var headerEnd = -1;
        while (headerEnd < 0)
        {
            var read = await stream.ReadAsync(buffer, cancellationToken);
            if (read == 0)
            {
                throw new InvalidDataException("Локальный HTTP-запрос оборван.");
            }

            request.Write(buffer, 0, read);
            if (request.Length > MaximumRequestBytes)
            {
                throw new InvalidDataException("Локальный HTTP-запрос слишком велик.");
            }

            headerEnd = FindHeaderEnd(request.GetBuffer(), (int)request.Length);
        }

        var bytes = request.GetBuffer();
        var headers = Encoding.ASCII.GetString(bytes, 0, headerEnd);
        var contentLength = ParseContentLength(headers);
        if (contentLength is <= 0 or > MaximumRequestBytes)
        {
            throw new InvalidDataException("Некорректная длина GSI payload.");
        }

        var bodyStart = headerEnd + 4;
        while (request.Length - bodyStart < contentLength)
        {
            var read = await stream.ReadAsync(buffer, cancellationToken);
            if (read == 0)
            {
                throw new InvalidDataException("GSI payload оборван.");
            }

            request.Write(buffer, 0, read);
            if (request.Length > MaximumRequestBytes)
            {
                throw new InvalidDataException("GSI payload слишком велик.");
            }
        }

        var body = new byte[contentLength];
        Array.Copy(request.GetBuffer(), bodyStart, body, 0, contentLength);
        return body;
    }

    private static int FindHeaderEnd(byte[] buffer, int length)
    {
        for (var index = 0; index <= length - 4; index++)
        {
            if (buffer[index] == '\r' && buffer[index + 1] == '\n' &&
                buffer[index + 2] == '\r' && buffer[index + 3] == '\n')
            {
                return index;
            }
        }

        return -1;
    }

    private static int ParseContentLength(string headers)
    {
        foreach (var line in headers.Split("\r\n", StringSplitOptions.RemoveEmptyEntries))
        {
            const string prefix = "Content-Length:";
            if (line.StartsWith(prefix, StringComparison.OrdinalIgnoreCase) &&
                int.TryParse(line[prefix.Length..].Trim(), out var length))
            {
                return length;
            }
        }

        return -1;
    }

    private void UpdateGameState(byte[] body)
    {
        using var document = JsonDocument.Parse(body);
        var root = document.RootElement;
        if (!root.TryGetProperty("auth", out var auth) ||
            !auth.TryGetProperty("token", out var token) ||
            !string.Equals(token.GetString(), AuthenticationToken, StringComparison.Ordinal) ||
            !root.TryGetProperty("provider", out var provider) ||
            !provider.TryGetProperty("appid", out var appId) ||
            !IsDotaAppId(appId) ||
            !root.TryGetProperty("map", out var map) ||
            !map.TryGetProperty("game_state", out var gameState))
        {
            return;
        }

        lock (_syncRoot)
        {
            _gameState = gameState.GetString();
            _gameStateReceivedAt = DateTimeOffset.UtcNow;
        }
    }

    private static bool IsDotaAppId(JsonElement appId) =>
        appId.ValueKind == JsonValueKind.Number
            ? appId.TryGetInt32(out var value) && value == 570
            : appId.ValueKind == JsonValueKind.String &&
              string.Equals(appId.GetString(), "570", StringComparison.Ordinal);

    [SupportedOSPlatform("windows")]
    private static bool TryGetForegroundDotaProcess(
        out Process process,
        out string error)
    {
        process = null!;
        var foreground = GetForegroundWindow();
        if (foreground == 0)
        {
            error = "Не удалось определить активное окно. Переключись в Dota 2.";
            return false;
        }

        _ = GetWindowThreadProcessId(foreground, out var processId);
        try
        {
            process = Process.GetProcessById((int)processId);
            if (!string.Equals(process.ProcessName, "dota2", StringComparison.OrdinalIgnoreCase) ||
                process.MainWindowHandle != foreground)
            {
                process.Dispose();
                process = null!;
                error = "Перед пиком активным окном должна быть именно Dota 2.";
                return false;
            }

            error = string.Empty;
            return true;
        }
        catch (Exception exception) when (
            exception is ArgumentException or InvalidOperationException)
        {
            error = "Окно Dota 2 закрылось до выполнения команды.";
            return false;
        }
    }

    [SupportedOSPlatform("windows")]
    private static bool IsStillForegroundDota(int expectedProcessId)
    {
        var foreground = GetForegroundWindow();
        _ = GetWindowThreadProcessId(foreground, out var processId);
        return processId == (uint)expectedProcessId;
    }

    private static bool IsSafeSearchText(string value) =>
        !string.IsNullOrWhiteSpace(value) &&
        value.Length <= 80 &&
        value.All(character =>
            char.IsAsciiLetterOrDigit(character) || character is ' ' or '-' or '_' or '\'');

    private static string BuildWindowsInputError(string action)
    {
        var error = Marshal.GetLastPInvokeError();
        var suffix = error == 0
            ? string.Empty
            : $" Код Win32 {error}: {new Win32Exception(error).Message}.";
        return $"Windows не приняла {action} в Dota 2. " +
               "Убедись, что Dota 2 и Egorik запущены с одинаковыми правами " +
               "(лучше оба без запуска от администратора)." + suffix;
    }

    [SupportedOSPlatform("windows")]
    private static bool ClickHeroConfirmButton(nint windowHandle)
    {
        if (!GetClientRect(windowHandle, out var clientRect))
        {
            return false;
        }

        var width = clientRect.Right - clientRect.Left;
        var height = clientRect.Bottom - clientRect.Top;
        if (width < 800 || height < 600)
        {
            return false;
        }

        var target = HeroConfirmPointForClient(width, height);
        var screenPoint = new NativePoint
        {
            X = target.X,
            Y = target.Y
        };
        if (!ClientToScreen(windowHandle, ref screenPoint) ||
            !GetCursorPos(out var originalCursor) ||
            !SetCursorPos(screenPoint.X, screenPoint.Y))
        {
            return false;
        }

        try
        {
            Input[] inputs =
            [
                MouseInput(MouseEventLeftDown),
                MouseInput(MouseEventLeftUp)
            ];
            return SendInput((uint)inputs.Length, inputs, Input.Size) == inputs.Length;
        }
        finally
        {
            _ = SetCursorPos(originalCursor.X, originalCursor.Y);
        }
    }

    [SupportedOSPlatform("windows")]
    private static bool SendRepeatedKey(ushort virtualKey, int count)
    {
        for (var index = 0; index < count; index++)
        {
            if (!SendKey(virtualKey))
            {
                return false;
            }
        }

        return true;
    }

    [SupportedOSPlatform("windows")]
    private static bool SendKey(ushort virtualKey)
    {
        Input[] inputs =
        [
            KeyboardInput(virtualKey, 0),
            KeyboardInput(virtualKey, KeyEventKeyUp)
        ];
        return SendInput((uint)inputs.Length, inputs, Input.Size) == inputs.Length;
    }

    [SupportedOSPlatform("windows")]
    private static bool SendUnicodeText(string value)
    {
        var inputs = new List<Input>(value.Length * 2);
        foreach (var character in value)
        {
            inputs.Add(UnicodeInput(character, 0));
            inputs.Add(UnicodeInput(character, KeyEventKeyUp));
        }

        return SendInput(
                   (uint)inputs.Count,
                   inputs.ToArray(),
                   Input.Size) == inputs.Count;
    }

    private static Input KeyboardInput(ushort virtualKey, uint flags) =>
        new()
        {
            Type = InputKeyboard,
            Data = new InputUnion
            {
                Keyboard = new KeyboardInputData
                {
                    VirtualKey = virtualKey,
                    Flags = flags
                }
            }
        };

    private static Input UnicodeInput(char character, uint flags) =>
        new()
        {
            Type = InputKeyboard,
            Data = new InputUnion
            {
                Keyboard = new KeyboardInputData
                {
                    ScanCode = character,
                    Flags = KeyEventUnicode | flags
                }
            }
        };

    private static Input MouseInput(uint flags) =>
        new()
        {
            Type = InputMouse,
            Data = new InputUnion
            {
                Mouse = new MouseInputData
                {
                    Flags = flags
                }
            }
        };

    private const uint InputMouse = 0;
    private const uint InputKeyboard = 1;
    private const uint MouseEventLeftDown = 0x0002;
    private const uint MouseEventLeftUp = 0x0004;
    private const uint KeyEventKeyUp = 0x0002;
    private const uint KeyEventUnicode = 0x0004;
    private const ushort VirtualKeyBack = 0x08;
    private const ushort VirtualKeyReturn = 0x0D;

    [StructLayout(LayoutKind.Sequential)]
    private struct Input
    {
        public static readonly int Size = Marshal.SizeOf<Input>();

        public uint Type;
        public InputUnion Data;
    }

    [StructLayout(LayoutKind.Explicit)]
    private struct InputUnion
    {
        [FieldOffset(0)]
        public MouseInputData Mouse;

        [FieldOffset(0)]
        public KeyboardInputData Keyboard;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct MouseInputData
    {
        public int X;
        public int Y;
        public uint MouseData;
        public uint Flags;
        public uint Time;
        public nuint ExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct KeyboardInputData
    {
        public ushort VirtualKey;
        public ushort ScanCode;
        public uint Flags;
        public uint Time;
        public nuint ExtraInfo;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct NativePoint
    {
        public int X;
        public int Y;
    }

    [StructLayout(LayoutKind.Sequential)]
    private struct NativeRect
    {
        public int Left;
        public int Top;
        public int Right;
        public int Bottom;
    }

